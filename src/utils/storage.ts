import { Paper, ComparisonResult, ResearchGapResult, Language } from '../types';
import { SAMPLE_PAPERS } from '../data/samplePapers';

const STORAGE_KEYS = {
  PAPERS: 'papermind_papers_v1',
  ACTIVE_PAPER_ID: 'papermind_active_paper_id',
  COMPARISONS: 'papermind_comparisons_v1',
  GAPS: 'papermind_gaps_v1',
  SCRATCHPAD: 'papermind_scratchpad_v1',
  THEME: 'papermind_theme_mode',
  LANGUAGE: 'papermind_ui_lang',
};

export function loadStoredPapers(): Paper[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.PAPERS);
    if (!raw) {
      saveStoredPapers(SAMPLE_PAPERS);
      return SAMPLE_PAPERS;
    }
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed) || parsed.length === 0) {
      saveStoredPapers(SAMPLE_PAPERS);
      return SAMPLE_PAPERS;
    }
    return parsed;
  } catch (e) {
    console.error('Error loading papers from storage:', e);
    return SAMPLE_PAPERS;
  }
}

export function saveStoredPapers(papers: Paper[]): void {
  try {
    localStorage.setItem(STORAGE_KEYS.PAPERS, JSON.stringify(papers));
  } catch (e) {
    console.error('Error saving papers to storage:', e);
  }
}

