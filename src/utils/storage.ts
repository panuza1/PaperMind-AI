// Markdown export utilities
export function downloadMarkdownFile(filename: string, content: string) {
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename.endsWith('.md') ? filename : `${filename}.md`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function exportSummaryToMarkdown(paper: Paper): string {
  if (!paper.summary) return `# ${paper.title}\n\nNo summary available yet.`;

  const s = paper.summary;
  let md = `# Research Paper Summary: ${paper.title}\n\n`;
  md += `**Authors**: ${paper.authors} (${paper.year})\n`;
  md += `**Total Pages**: ${paper.totalPages} | **Generated by**: PaperMind AI\n\n`;
  md += `> **Key Takeaway**: ${s.quickTakeaway}\n\n`;
  
  md += `## 1. Executive Summary\n\n${s.executiveSummary}\n\n`;
  md += `## 2. Problem Statement & Motivation\n\n${s.problemStatement}\n\n`;
  
  md += `## 3. Methodology & Technical Architecture\n\n`;
  md += `- **Architecture**: ${s.methodology.architecture}\n`;
  md += `- **Key Innovations**:\n`;
  s.methodology.keyInnovations.forEach(i => md += `  - ${i}\n`);
  md += `- **Setup & Compute**: ${s.methodology.trainingOrExperimentalSetup}\n\n`;

  md += `## 4. Key Findings & Empirical Results\n\n`;
  md += `| Metric / Benchmark | Result | Page Reference | Interpretation |\n`;
  md += `| ------------------ | ------ | -------------- | -------------- |\n`;
  s.keyFindings.forEach(f => {
    md += `| ${f.metricOrFinding} | ${f.result} | Page ${f.pageReference} | ${f.interpretation} |\n`;
  });
  md += `\n`;

  md += `## 5. Architectural Strengths\n\n`;
  s.strengths.forEach(st => md += `- ${st}\n`);
  md += `\n`;

  md += `## 6. Limitations & Assumptions\n\n`;
  s.limitations.forEach(l => md += `- ${l}\n`);
  md += `\n`;

  md += `## 7. Practical Applications\n\n`;
  s.practicalApplications.forEach(a => md += `- ${a}\n`);
  md += `\n`;

  md += `## Keywords\n\n`;
  md += s.keywords.map(k => `\`${k}\``).join(' ') + '\n';

  return md;
}

export function exportComparisonToMarkdown(comparison: ComparisonResult): string {
  let md = `# Multi-Paper Comparison: ${comparison.comparisonTitle}\n\n`;
  md += `**Compared Papers**:\n`;
  comparison.paperTitles.forEach(t => md += `- ${t}\n`);
  md += `\n**Date**: ${new Date(comparison.createdAt).toLocaleDateString()}\n\n`;

  md += `## Synthesis & Paradigm Overview\n\n${comparison.synthesisOverview}\n\n`;

  md += `## Comparative Dimensions\n\n`;
  comparison.dimensions.forEach(dim => {
    md += `### ${dim.dimension}\n\n`;
    dim.paperAssessments.forEach(pa => {
      md += `- **${pa.paperTitle}**: ${pa.assessment} *(${pa.ratingOrHighlight})*\n`;
    });
    md += `\n`;
  });

  md += `## Shared Principles (Common Ground)\n\n`;
  comparison.commonGround.forEach(cg => md += `- ${cg}\n`);
  md += `\n`;

  md += `## Key Divergences & Trade-offs\n\n`;
  comparison.keyDivergences.forEach(kd => md += `- ${kd}\n`);
  md += `\n`;

  md += `## Decision & Selection Guide\n\n`;
  md += `| Scenario / Use Case | Recommended Paper | Rationale |\n`;
  md += `| ------------------- | ----------------- | --------- |\n`;
  comparison.selectionGuide.forEach(sg => {
    md += `| ${sg.scenario} | **${sg.recommendedPaper}** | ${sg.rationale} |\n`;
  });
  md += `\n`;

  return md;
}

export function exportGapsToMarkdown(gaps: ResearchGapResult): string {
  let md = `# Research Gaps & Novel Opportunities Dossier\n\n`;
  md += `**Analyzed Papers**:\n`;
  gaps.paperTitles.forEach(t => md += `- ${t}\n`);
  md += `\n**Domain Overview**:\n${gaps.domainOverview}\n\n`;

  md += `## Identified Research Gaps\n\n`;
  gaps.identifiedGaps.forEach((g, idx) => {
    md += `### ${idx + 1}. [${g.category}] ${g.title} (${g.severity} Priority)\n\n`;
    md += `- **Gap Description**: ${g.gapDescription}\n`;
    md += `- **Why It Matters**: ${g.whyItMatters}\n`;
    md += `- **Current Limitation in Literature**: ${g.currentPaperLimitation}\n`;
    md += `- **Testable Hypothesis**: *${g.proposedHypothesis}*\n`;
    md += `- **Proposed Methodology**: ${g.suggestedMethodology}\n`;
    md += `- **Target Scope**: \`${g.difficultyLevel}\`\n\n`;
  });

  md += `## Emerging Cross-Domain Trends\n\n`;
  gaps.emergingTrends.forEach(t => md += `- ${t}\n`);
  md += `\n`;

  md += `## Grant / Thesis Proposal Pitch\n\n${gaps.grantProposalHook}\n\n`;

  return md;
}
